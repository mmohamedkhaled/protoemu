"""Wrap a firmware program around the real state machine, for formal proofs.

usage: fw_gen.py <program.pio> <output.v>

Writes a module `<program>_sm`: pe_sm with its instruction port wired to a ROM
holding the assembled program, and its configuration fixed to what the program
declares. Pin numbers are module parameters. Each label becomes a define,
`FW_<PROGRAM>_<LABEL>`, so a property can refer to the program's routines.

The proofs therefore run on the firmware exactly as it is in firmware/, through
the same assembler the host uses.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))

import asm  # noqa: E402


def generate(source, out):
    prog = asm.assemble_file(source)
    name = prog.name or os.path.splitext(os.path.basename(source))[0]
    cfg = dict(in_dir=0, out_dir=0, autopush=0, autopull=0, push_thresh=0, pull_thresh=0,
               set_count=0)
    cfg.update(prog.sm_config())

    lines = [f"// Generated by formal/fw_gen.py from {os.path.basename(source)}. Do not edit.",
             "`default_nettype none", ""]
    for label, addr in sorted(prog.labels.items()):
        lines.append(f"`define FW_{name.upper()}_{label.upper()} 5'd{addr}")
    lines.append(f"`define FW_{name.upper()}_LAST 5'd{len(prog.words) - 1}")
    lines.append("`ifndef FORMAL")
    lines.append("  `error fw_gen.py output is for formal proofs only")
    lines.append("`endif")
    lines += ["", f"module {name}_sm #(",
              "    parameter [2:0] IN_BASE = 3'd0, OUT_BASE = 3'd0, SET_BASE = 3'd0,",
              "    parameter [2:0] SIDE_BASE = 3'd0, JMP_PIN = 3'd0",
              ") (",
              "    input  wire        clk, rst_n, tick,",
              "    input  wire [7:0]  pins_in,",
              "    input  wire [31:0] tx_data, timer,",
              "    input  wire        tx_empty, rx_full,",
              "    output wire [4:0]  pc,",
              "    output wire [7:0]  out_mask, out_val, dir_mask, dir_val,",
              "    output wire        tx_pop, rx_push, trig_fire, timer_reset, stalled,",
              "    output wire [31:0] rx_data, f_osr",
              ");",
              "  reg [15:0] instr;",
              "  always @(*) begin",
              "    case (pc)"]
    for addr, word in enumerate(prog.words):
        lines.append(f"      5'd{addr}: instr = 16'h{word:04x};")
    lines += ["      default: instr = 16'ha042;  // nop; never reached, see the pc property",
              "    endcase",
              "  end",
              "",
              "  wire flag_illegal, flag_rxover;",
              "  pe_sm sm (",
              "      .clk(clk), .rst_n(rst_n), .tick(tick), .restart(1'b0),",
              "      .pc_wr(1'b0), .pc_wdata(5'd0), .pc(pc), .instr(instr),",
              f"      .wrap_bottom(5'd{cfg['wrap_bottom']}), .wrap_top(5'd{cfg['wrap_top']}),",
              "      .in_base(IN_BASE), .out_base(OUT_BASE), .set_base(SET_BASE),",
              f"      .set_count(3'd{cfg['set_count']}), .side_base(SIDE_BASE),",
              f"      .side_cnt(2'd{cfg['side_cnt']}), .side_opt(1'b{cfg['side_opt']}),",
              f"      .side_pindir(1'b{cfg['side_pindir']}), .jmp_pin(JMP_PIN),",
              f"      .in_dir(1'b{cfg['in_dir']}), .out_dir(1'b{cfg['out_dir']}),",
              f"      .autopush(1'b{cfg['autopush']}), .autopull(1'b{cfg['autopull']}),",
              f"      .push_thresh(5'd{cfg['push_thresh']}), .pull_thresh(5'd{cfg['pull_thresh']}),",
              "      .pins_in(pins_in), .out_mask(out_mask), .out_val(out_val),",
              "      .dir_mask(dir_mask), .dir_val(dir_val),",
              "      .tx_data(tx_data), .tx_empty(tx_empty), .tx_pop(tx_pop),",
              "      .rx_data(rx_data), .rx_full(rx_full), .rx_push(rx_push),",
              "      .timer(timer), .trig_fire(trig_fire), .timer_reset(timer_reset),",
              "      .flag_illegal(flag_illegal), .flag_rxover(flag_rxover), .stalled(stalled),",
              "      .f_osr(f_osr)",
              "  );",
              "",
              "  wire _unused = &{flag_rxover, 1'b0};",
              "",
              "`ifdef FORMAL",
              "  // The program never runs off its end, and never meets an illegal word.",
              f"  always @(*) if (rst_n) assert (pc <= `FW_{name.upper()}_LAST);",
              "  always @(*) if (rst_n) assert (!flag_illegal);",
              "`endif",
              "endmodule", ""]
    with open(out, "w", newline="\n") as handle:
        handle.write("\n".join(lines))


if __name__ == "__main__":
    generate(sys.argv[1], sys.argv[2])
